-- Sothema HR Intelligence hosted proof-of-concept schema.
-- Run once in the Supabase SQL Editor. Keep the candidate-cvs bucket private.
create table if not exists public.ats_candidates (
    id bigint generated by default as identity primary key,
    fingerprint text not null unique,
    source_filename text not null,
    storage_key text not null,
    file_type text not null check (file_type in ('pdf', 'docx')),
    file_size bigint not null default 0,
    full_name text not null default '',
    email text not null default '',
    phone text not null default '',
    summary text not null default '',
    raw_text text not null default '',
    structured_json jsonb not null default '{}'::jsonb,
    local_analysis_json jsonb not null default '{}'::jsonb,
    ai_analysis_json jsonb,
    score integer,
    confidence double precision,
    processing text not null default 'ready',
    review text not null default 'a_examiner' check (review in ('a_examiner','en_revue','retenu','en_attente','archive')),
    notes text not null default '',
    reviewed_by text,
    reviewed_at timestamptz,
    created_by text not null default '',
    target_role text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists ix_ats_candidates_email on public.ats_candidates (lower(email));
create index if not exists ix_ats_candidates_review on public.ats_candidates (review);
create index if not exists ix_ats_candidates_created_at on public.ats_candidates (created_at desc);

create table if not exists public.ats_audit_log (
    id bigint generated by default as identity primary key,
    action text not null,
    candidate_id bigint,
    details text,
    created_at timestamptz not null default now(),
    actor text not null default ''
);
create index if not exists ix_ats_audit_candidate on public.ats_audit_log (candidate_id, id desc);
create index if not exists ix_ats_audit_created_at on public.ats_audit_log (created_at desc);

create table if not exists public.admin (
    id bigint generated by default as identity primary key,
    email text not null unique,
    password text not null,
    created_at timestamptz not null default now()
);
create table if not exists public.admin_logs (
    id bigint generated by default as identity primary key,
    admin_email text not null,
    action text not null,
    timestamp timestamptz not null default now()
);

-- Explicit table grants for the Python service-role client. RLS has no public policies.
revoke all on public.ats_candidates, public.ats_audit_log, public.admin, public.admin_logs
    from public, anon, authenticated;
revoke all on all sequences in schema public from public, anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update, delete on public.ats_candidates, public.ats_audit_log,
    public.admin, public.admin_logs to service_role;
grant usage, select on all sequences in schema public to service_role;

-- These tables are accessed only by the server-side Supabase service role from Streamlit.
-- Do not expose the service-role key to a browser. Enable RLS and leave anon/authenticated
-- without policies so direct client access is denied.
alter table public.ats_candidates enable row level security;
alter table public.ats_audit_log enable row level security;
alter table public.admin enable row level security;
alter table public.admin_logs enable row level security;

-- Atomic helper: insert candidate and corresponding audit record in the same Postgres transaction.
create or replace function public.ats_ingest_candidate(p_candidate jsonb)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    new_id bigint;
begin
    insert into public.ats_candidates (
        fingerprint, source_filename, storage_key, file_type, file_size, full_name,
        email, phone, summary, raw_text, structured_json, local_analysis_json,
        score, confidence, processing, review, target_role, created_by
    ) values (
        p_candidate->>'fingerprint', p_candidate->>'source_filename', p_candidate->>'storage_key',
        p_candidate->>'file_type', coalesce((p_candidate->>'file_size')::bigint, 0),
        coalesce(p_candidate->>'full_name', ''), coalesce(p_candidate->>'email', ''),
        coalesce(p_candidate->>'phone', ''), coalesce(p_candidate->>'summary', ''),
        coalesce(p_candidate->>'raw_text', ''), coalesce(p_candidate->'structured_json', '{}'::jsonb),
        coalesce(p_candidate->'local_analysis_json', '{}'::jsonb),
        nullif(p_candidate->>'score', '')::integer, nullif(p_candidate->>'confidence', '')::double precision,
        'ready', 'a_examiner', coalesce(p_candidate->>'target_role', ''), coalesce(p_candidate->>'created_by', '')
    ) returning id into new_id;
    insert into public.ats_audit_log(action, candidate_id, details, actor)
    values ('candidate_ingested', new_id,
        jsonb_build_object('filename', p_candidate->>'source_filename', 'sha256', p_candidate->>'fingerprint',
                           'score', p_candidate->>'score', 'confidence', p_candidate->>'confidence')::text,
        coalesce(p_candidate->>'created_by', ''));
    return new_id;
end;
$$;

-- Atomic helper for RH review status changes and their audit event.
create or replace function public.ats_set_review(p_ids bigint[], p_review text, p_actor text)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
    item_id bigint;
    old_review text;
begin
    if p_review not in ('a_examiner','en_revue','retenu','en_attente','archive') then
        raise exception 'Invalid review status';
    end if;
    foreach item_id in array p_ids loop
        select review into old_review from public.ats_candidates where id = item_id for update;
        if found and old_review is distinct from p_review then
            update public.ats_candidates set review=p_review, updated_at=now() where id=item_id;
            insert into public.ats_audit_log(action,candidate_id,details,actor)
            values ('review_status_changed',item_id,jsonb_build_object('from',old_review,'to',p_review)::text,coalesce(p_actor,''));
        end if;
    end loop;
end;
$$;

create or replace function public.ats_validate_analysis(p_id bigint, p_actor text)
returns void language plpgsql security invoker set search_path=public as $$
begin
    update public.ats_candidates set reviewed_by=p_actor, reviewed_at=now(), updated_at=now() where id=p_id;
    if not found then raise exception 'Candidate not found'; end if;
    insert into public.ats_audit_log(action,candidate_id,actor) values ('analysis_validated',p_id,coalesce(p_actor,''));
end; $$;

create or replace function public.ats_save_notes(p_id bigint,p_notes text,p_actor text)
returns void language plpgsql security invoker set search_path=public as $$
begin
    update public.ats_candidates set notes=left(coalesce(p_notes,''),4000), updated_at=now() where id=p_id;
    if not found then raise exception 'Candidate not found'; end if;
    insert into public.ats_audit_log(action,candidate_id,details,actor)
    values ('notes_saved',p_id,jsonb_build_object('length',length(left(coalesce(p_notes,''),4000)))::text,coalesce(p_actor,''));
end; $$;

create or replace function public.ats_update_analysis(p_id bigint,p_analysis jsonb,p_score integer,p_confidence double precision,p_role text,p_actor text)
returns void language plpgsql security invoker set search_path=public as $$
declare old_score integer;
begin
    select score into old_score from public.ats_candidates where id=p_id for update;
    if not found then raise exception 'Candidate not found'; end if;
    update public.ats_candidates set local_analysis_json=p_analysis, structured_json=p_analysis, score=p_score,
        confidence=p_confidence, target_role=coalesce(p_role,''), reviewed_by=null, reviewed_at=null, updated_at=now()
        where id=p_id;
    insert into public.ats_audit_log(action,candidate_id,details,actor)
    values ('analysis_rerun',p_id,jsonb_build_object('criteria',coalesce(p_role,'générale'),'previous_score',old_score,'score',p_score)::text,coalesce(p_actor,''));
end; $$;

create or replace function public.ats_save_ai_result(p_id bigint,p_result jsonb,p_actor text)
returns void language plpgsql security invoker set search_path=public as $$
begin
    update public.ats_candidates set ai_analysis_json=p_result, updated_at=now() where id=p_id;
    if not found then raise exception 'Candidate not found'; end if;
    insert into public.ats_audit_log(action,candidate_id,details,actor)
    values ('ai_analysis_saved',p_id,coalesce(p_result->>'provider',''),coalesce(p_actor,''));
end; $$;

create or replace function public.ats_delete_candidates(p_ids bigint[],p_actor text)
returns void language plpgsql security invoker set search_path=public as $$
declare item_id bigint; old_file text; old_hash text;
begin
    foreach item_id in array p_ids loop
        select source_filename,fingerprint into old_file,old_hash from public.ats_candidates where id=item_id for update;
        if found then
            delete from public.ats_candidates where id=item_id;
            insert into public.ats_audit_log(action,candidate_id,details,actor)
            values ('candidate_deleted',item_id,jsonb_build_object('filename',old_file,'sha256',old_hash)::text,coalesce(p_actor,''));
        end if;
    end loop;
end; $$;

create or replace function public.ats_log_event(p_action text,p_candidate_id bigint,p_details text,p_actor text)
returns void language sql security invoker set search_path=public as $$
    insert into public.ats_audit_log(action,candidate_id,details,actor)
    values (p_action,p_candidate_id,p_details,coalesce(p_actor,''));
$$;

create or replace function public.ats_admin_count()
returns bigint language sql security invoker set search_path=public as $$ select count(*) from public.admin; $$;

create or replace function public.ats_update_admin_password(p_email text,p_password text)
returns boolean language plpgsql security invoker set search_path=public as $$
begin
    update public.admin set password=p_password where email=lower(trim(p_email));
    return found;
end; $$;

create or replace function public.ats_add_admin(p_email text,p_password text)
returns boolean language plpgsql security invoker set search_path=public as $$
begin
    insert into public.admin(email,password) values(lower(trim(p_email)),p_password);
    return true;
exception when unique_violation then return false;
end; $$;

create or replace function public.ats_create_first_admin(p_email text,p_password text)
returns boolean language plpgsql security invoker set search_path=public as $$
begin
    lock table public.admin in exclusive mode;
    if exists(select 1 from public.admin) then return false; end if;
    insert into public.admin(email,password) values(lower(trim(p_email)),p_password);
    insert into public.ats_audit_log(action,details,actor)
    values ('admin_created',jsonb_build_object('email',lower(trim(p_email)),'first_run',true)::text,lower(trim(p_email)));
    return true;
exception when unique_violation then return false;
end; $$;

create or replace function public.ats_log_admin_action(p_email text,p_action text)
returns void language plpgsql security invoker set search_path=public as $$
begin
    insert into public.admin_logs(admin_email,action) values(lower(trim(p_email)),p_action);
end; $$;

